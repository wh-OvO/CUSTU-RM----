/**
  ******************************************************************************
  * @file    arm_cfg.c
  * @brief   四个关节的标定表 —— **标定就是改这个文件里的数**
  ******************************************************************************
  * @note    标定流程（没有示波器也能做，见 docs/T1_角度脉宽映射_说明.md）：
  *
  *          1) 先把 us_at_deg_min / us_at_deg_max 都填 SERVO_US_SAFE_MIN / MAX，
  *             上电看舵机转不转、有没有顶死异响。
  *          2) 用 arm_set_us() 直接给脉宽，从 1500 开始每次 ±50µs，
  *             直到舵机**刚好**走到机械端点、但不卡不响，记下这两个 µs 值。
  *          3) 把这两个值填进 us_at_deg_min / us_at_deg_max。
  *          4) 量一下这两个端点之间实际转了多少度，填进 deg_min / deg_max。
  *             懒得量就按 180° 填，先跑通再精修。
  *
  * @warning 下面表格里的数值是**出厂占位值**，不是标定结果。
  *          第一次上电前请确认 SERVO_US_SAFE_MIN/MAX 是 600/2400，
  *          这能保证就算表格写错，舵机也不会被顶到堵转。
  ******************************************************************************
  */

#include "arm_cfg.h"

/* ==========================================================================
 * 关节 ↔ 定时器通道 ↔ 引脚 对照
 *
 *   关节   定时器通道     芯片引脚     CubeMX 里的标签
 *   ----   -----------    --------     ---------------
 *   J1     TIM2_CH1       PA0          TIM2_CH1
 *   J2     TIM2_CH2       PA1          TIM2_CH2
 *   J3     TIM2_CH3       PA2          TIM2_CH3
 *   J4     TIM2_CH4       PA3          TIM2_CH4
 *
 *   顺序不能乱改：arm_pwm.c 里的 s_channel[] 按同样顺序映射通道，
 *   改了这个顺序就要同步改那张表，否则 J2 的指令会打到 J3 上。
 * ========================================================================== */

const arm_joint_cfg_t g_arm_joint[ARM_JOINT_NUM] =
{
  /* ---- J1 底座回转（PA0 / TIM2_CH1）----------------------------------
   * 一般行程最大，装好后左右各能转 90° 左右；
   * 如果转到某个方向会撞到底座，把 deg_min / deg_max 收窄。
   */
  {
    .name           = "J1 底座",
    .deg_min        = 0,
    .deg_max        = 180,
    .deg_home       = 90,
    .us_at_deg_min  = 600,      /* ← 标定后改这里 */
    .us_at_deg_max  = 2400,     /* ← 标定后改这里 */
  },

  /* ---- J2 大臂（PA1 / TIM2_CH2）--------------------------------------
   * 抬升关节，负载最大。**行程要留余量**，大臂顶到极限最容易堵转烧舵机。
   */
  {
    .name           = "J2 大臂",
    .deg_min        = 0,
    .deg_max        = 180,
    .deg_home       = 90,
    .us_at_deg_min  = 600,      /* ← 标定后改这里 */
    .us_at_deg_max  = 2400,     /* ← 标定后改这里 */
  },

  /* ---- J3 小臂（PA2 / TIM2_CH3）--------------------------------------
   * 和 J2 类似，但负载小。如果装反了（角度增大反而往下压），
   * 把下面两个 µs 值**对调**即可，不用改代码逻辑。
   */
  {
    .name           = "J3 小臂",
    .deg_min        = 0,
    .deg_max        = 180,
    .deg_home       = 90,
    .us_at_deg_min  = 600,      /* ← 标定后改这里 */
    .us_at_deg_max  = 2400,     /* ← 标定后改这里 */
  },

  /* ---- J4 夹爪（PA3 / TIM2_CH4）--------------------------------------
   * 只开合，行程小。逻辑角度用 0~60 表示「闭 → 开」，
   * 这样上层协议里 0.1° 的数值仍然有意义（0 = 全闭，600 = 全开）。
   */
  {
    .name           = "J4 夹爪",
    .deg_min        = 0,
    .deg_max        = 60,
    .deg_home       = 30,
    .us_at_deg_min  = 600,      /* ← 标定后改这里 */
    .us_at_deg_max  = 2400,     /* ← 标定后改这里 */
  },
};
