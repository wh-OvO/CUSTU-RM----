/**
  ******************************************************************************
  * @file    arm_cfg.c
  * @brief   四个关节的标定表 —— **标定就是改这个文件里的数**
  ******************************************************************************
  * @note    标定流程（没有示波器也能做，见 docs/调试帧_0x31_0x32_标定说明.md）：
  *
  *          1) 先把 us_at_deg_min / us_at_deg_max 临时填成 500 / 2500，
  *             上电看舵机转不转、有没有顶死异响。
  *          2) 用上位机调试页（0x31 帧）直接给脉宽，从 1500 开始每次 ±50µs，
  *             直到舵机**刚好**走到机械端点、但不卡不响，记下这两个 µs 值。
  *             上位机上按一次按钮就生效，不用改代码重烧。
  *          3) 把这两个值**各往回收 40~50µs**，再填进 us_at_deg_min / us_at_deg_max。
  *             留余量是因为工程里已经没有"安全窗"兜底了（2026-11-09 删掉），
  *             这张表就是唯一的防线：端点贴着机械限位，温度一变就可能顶死。
  *          4) 量一下这两个端点之间实际转了多少度，填进 deg_min / deg_max。
  *             懒得量就按 180° 填，先跑通再精修。
  *
  * @warning 下面表格里的数值是**出厂占位值**，不是标定结果。
  *          第一次上电前记得按上面第 1 步改成 500/2500 先探路 ——
  *          占位值 600/2400 虽然保守，但它和真实行程没有任何关系。
  ******************************************************************************
  */

#include "arm_cfg.h"

/* ==========================================================================
 * 关节 ↔ 定时器通道 ↔ 引脚 对照
 *
 *   关节   定时器通道     芯片引脚     CubeMX 里的标签
 *   ----   -----------    --------     ---------------
 *   J1     TIM2_CH1       PA15         TIM2_CH1
 *   J2     TIM2_CH2       PB3          TIM2_CH2
 *   J3     TIM2_CH3       PB10         TIM2_CH3
 *   J4     TIM2_CH4       PB11         TIM2_CH4
 *
 *   ⚠️ 2026-11-11 从 Blue Pill 换到野火 F103C8T6 核心板后，四个脚都变了：
 *      原来是 PA0/PA1/PA2/PA3（野火板上是 KEY1 和 RGB 灯，不能占用），
 *      现在靠 TIM2 **全重映射**挪到 PA15/PB3/PB10/PB11。
 *      重映射写在哪：main.c 的 MX_GPIO_Init() 里
 *          __HAL_AFIO_REMAP_SWJ_NOJTAG();    ← PA15/PB3 出厂是 JTAG 脚
 *          __HAL_AFIO_REMAP_TIM2_ENABLE();   ← TIM2_REMAP = 11（全重映射）
 *      注意：下面这张表是**注释**，改脚不用动代码，CubeMX 会生成 AF 配置；
 *           但上面两行 remap 必须手工维护，CubeMX 不会帮你写。
 *
 *   顺序不能乱改：arm_pwm.c 里的 s_channel[] 按同样顺序映射通道，
 *   改了这个顺序就要同步改那张表，否则 J2 的指令会打到 J3 上。
 * ========================================================================== */

const arm_joint_cfg_t g_arm_joint[ARM_JOINT_NUM] =
{
  /* ---- J1 底座回转（PA15 / TIM2_CH1，全重映射）--------------------------
   * **唯一的特殊关节：按学长方案是 360° 连续旋转舵机。**
   *
   * 现在填的是 .kind = ARM_JOINT_POS —— 因为 360° 舵机和 AS5600 都还没到，
   * 手头只有普通 180° SG90，所以先当位置型跑，这样整个工程能立即编译验证。
   *
   * >>> 360° 舵机 + AS5600 到货后，只改下面三处： <<<
   *     1. .kind       = ARM_JOINT_VEL
   *     2. .deg_min    = -180   .deg_max = 180   .deg_home = 0
   *     3. .us_stop / .us_per_dps 按标定填（见 docs 里的连续舵机标定流程）
   *   再把 as5600.c 里的占位实现换成真的 I²C 读取。
   *   arm_joint.c 一行都不用动。
   */
  {
    .name           = "J1 底座",
    .kind           = ARM_JOINT_POS,   /* ← 360° 舵机到货后改 ARM_JOINT_VEL */
    .deg_min        = 0,
    .deg_max        = 180,
    .deg_home       = 90,
    .us_at_deg_min  = 600,      /* ← 标定后改这里 */
    .us_at_deg_max  = 2400,     /* ← 标定后改这里 */
    .us_stop        = 0,        /* ← 仅 VEL 用：零速脉宽，标定后填 1500 附近的值 */
    .us_per_dps     = 0.0f,     /* ← 仅 VEL 用：每 °/s 需要多少 µs */
  },

  /* ---- J2 大臂（PB3 / TIM2_CH2）#mg90s#--------------------------------------
   * 抬升关节，负载最大。**行程要留余量**，大臂顶到极限最容易堵转烧舵机。
   */
  {
    .name           = "J2 大臂",
    .kind           = ARM_JOINT_POS,
    .deg_min        = 0,
    .deg_max        = 180,
    .deg_home       = 90,
    .us_at_deg_min  = 500,      /* ← 标定后改这里 */
    .us_at_deg_max  = 2500,     /* ← 标定后改这里 */
    .us_stop        = 0,
    .us_per_dps     = 0.0f,
  },

  /* ---- J3 小臂（PB10 / TIM2_CH3）#mg90s#--------------------------------------
   * 和 J2 类似，但负载小。如果装反了（角度增大反而往下压），
   * 把下面两个 µs 值**对调**即可，不用改代码逻辑。
   */
  {
    .name           = "J3 小臂",
    .kind           = ARM_JOINT_POS,
    .deg_min        = 0,
    .deg_max        = 180,
    .deg_home       = 90,
    .us_at_deg_min  = 500,      /* ← 标定后改这里 */
    .us_at_deg_max  = 2500,     /* ← 标定后改这里 */
    .us_stop        = 0,
    .us_per_dps     = 0.0f,
  },

  /* ---- J4 夹爪（PB11 / TIM2_CH4）--------------------------------------
   * 2026-11-13 实物标定（用户实测，三个点线性度极好）：
   *     张角   0° → 1430 µs
   *     张角  60° → 1480 µs
   *     张角 120° → 1530 µs      ← 再往上就堵转，1530 是硬上限
   *   ⇒ 斜率 = (1530 − 1430) / 120 = 0.8333 µs/度
   *   ⇒ 零位取 60°（= 1480 µs），夹爪半开，既不顶死也不空转
   *
   * ⚠️ 这一路的分辨率比别的关节差一个数量级，**别当成 bug 去修**：
   *     0.8333 µs/度 ⇒ **1 µs 的脉宽 = 1.2° 的夹爪角**。
   *     协议里 0.1° 的精度在这一路是浪费的，上报的 q4 只会是 1.2° 的整数倍
   *     （1480 → 60.0°、1481 → 61.2°），曲线上看就是台阶。
   *     这是夹爪连杆的传动比决定的，不是代码问题。
   *     好消息：T2 的「同起同停」判据只点底座/肩/肘，**不含夹爪**。
   *
   * ⚠️ 上电顺序不受影响：`arm_init()` 先给 1500 µs（= 84°）再立刻改成 1480，
   *     两次写发生在同一个 20ms 周期内，舵机看到的第一拍就是 1480。
   */
  {
    .name           = "J4 夹爪",
    .kind           = ARM_JOINT_POS,
    .deg_min        = 0,        /* 全闭 */
    .deg_max        = 120,      /* 全开（再大就堵转） */
    .deg_home       = 60,       /* = 1480 µs，半开 */
    .us_at_deg_min  = 1430,     /* 实测：全闭 */
    .us_at_deg_max  = 1530,     /* 实测：全开，超过就堵转 */
    .us_stop        = 0,
    .us_per_dps     = 0.0f,
  },
};
